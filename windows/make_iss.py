"""Writes build-win/installer.iss for Inno Setup from versions-Windows.txt and stage/Windows/."""
import os, datetime, glob

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
stage = os.path.join(ROOT, "stage", "Windows")
os.makedirs(os.path.join(ROOT, "build-win"), exist_ok=True)
desc = {}
for line in open(os.path.join(ROOT, "plugins.txt"), encoding="utf-8"):
    if line.startswith("#") or not line.strip():
        continue
    parts = [p for p in line.rstrip("\n").split("  ") if p.strip()]
    desc[parts[1].strip()] = parts[-1].strip()

comps, files, icons = [], [], []
for line in open(os.path.join(ROOT, "versions-Windows.txt"), encoding="utf-8"):
    prefix, ver, name = line.strip().split(" ", 2)
    cid = prefix.lower()
    src = os.path.join(stage, prefix)
    comps.append(f'Name: "{cid}"; Description: "{name} {ver}  -  {desc.get(prefix, "")}"; Types: full custom')
    vst3 = glob.glob(os.path.join(src, "VST3", "*.vst3"))
    if not vst3:
        raise SystemExit(f"{prefix}: no VST3 in the zip")
    for v in vst3:
        b = os.path.basename(v)
        files.append(f'Source: "{v}\\*"; DestDir: "{{commoncf64}}\\VST3\\{b}"; Flags: recursesubdirs createallsubdirs ignoreversion; Components: {cid}')
    files.append(f'Source: "{os.path.join(src, "controls.txt")}"; DestDir: "{{app}}\\Guides"; DestName: "{name} - controls.txt"; Flags: ignoreversion; Components: {cid}')

guide = os.path.join(ROOT, "docs", "Mix System User Guide.pdf")
files.append(f'Source: "{guide}"; DestDir: "{{app}}\\Guides"; Flags: ignoreversion')
icons.append('Name: "{group}\\Mix System User Guide"; Filename: "{app}\\Guides\\Mix System User Guide.pdf"')
icons.append('Name: "{group}\\Uninstall the Mix System"; Filename: "{uninstallexe}"')

ver = os.environ.get("PKG_VER") or datetime.date.today().strftime("%Y.%m.%d")
iss = f"""; generated by windows/make_iss.py
[Setup]
AppId={{{{34200D48-65BC-4C61-8447-56DF53F8CAD1}}
AppName=Castle Danger Music Company Mix System
AppVersion={ver}
AppPublisher=Castle Danger Music Company
AppPublisherURL=https://castledangermusic.com
DefaultDirName={{autopf}}\\Castle Danger Music Company
DefaultGroupName=Castle Danger Music Company
DisableProgramGroupPage=yes
LicenseFile={os.path.join(ROOT, "LICENSE.txt")}
OutputDir={os.path.join(ROOT, "build-win")}
OutputBaseFilename=CDMC_master_system_installer-Windows
ArchitecturesAllowed=x64compatible
ArchitecturesInstallIn64BitMode=x64compatible
PrivilegesRequired=admin
WizardStyle=modern
Compression=lzma2/max
SolidCompression=yes
UninstallDisplayName=Castle Danger Music Company Mix System

[Types]
Name: "full"; Description: "The whole Mix System"
Name: "custom"; Description: "Pick the plugins"; Flags: iscustom

[Components]
""" + "\n".join(comps) + """

[Files]
""" + "\n".join(files) + """

[Icons]
""" + "\n".join(icons) + "\n"
open(os.path.join(ROOT, "build-win", "installer.iss"), "w", encoding="utf-8").write(iss)
print(iss)
